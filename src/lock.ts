import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { LOCK } from "./map";

/**
 * What the code said when a claim was last accepted. One line per claim, sorted, so git merges two
 * branches cleanly: `.gitattributes` sets the union driver, and a merge can leave two lines for one
 * claim. A claim passes when any of its lines matches the code as it is now.
 */
export interface LockEntry {
  id: string;
  /** Fingerprint of the claim's words and evidence. */
  fp: string;
  /** `path#symbol` to hash. */
  anchors: Record<string, string>;
  /** Why the claim still holds after its code changed. Empty until someone confirms it. */
  reason: string;
}

const HEADER = "# stemap lock v1. Generated by stemap write and stemap confirm. Do not edit.\n";
const clean = (s: string) => s.replace(/\s+/g, " ").trim();

export function parseLock(text: string): Map<string, LockEntry[]> {
  const out = new Map<string, LockEntry[]>();
  for (const line of text.split("\n")) {
    if (!line || line.startsWith("#")) continue;
    const [id, fp, anchors, reason] = line.split("\t");
    if (!id || !fp) continue;
    const entry: LockEntry = { id, fp, reason: reason ?? "", anchors: {} };
    for (const a of (anchors ?? "").split(" ")) {
      const at = a.lastIndexOf("=");
      if (at > 0) entry.anchors[a.slice(0, at).replaceAll("\u00a0", " ")] = a.slice(at + 1);
    }
    out.set(id, [...(out.get(id) ?? []), entry]);
  }
  return out;
}

export function formatLock(lock: Map<string, LockEntry[]>): string {
  const lines: string[] = [];
  for (const id of [...lock.keys()].sort()) {
    for (const e of lock.get(id)!) {
      // A symbol can hold a space (`get(/a b)`), and a space separates anchors.
      const anchors = Object.keys(e.anchors).sort().map((a) => `${a.replaceAll(" ", "\u00a0")}=${e.anchors[a]}`).join(" ");
      lines.push([e.id, e.fp, anchors, clean(e.reason)].join("\t"));
    }
  }
  return HEADER + lines.join("\n") + (lines.length ? "\n" : "");
}

export const readLock = (dir: string) => {
  const f = join(dir, LOCK);
  return parseLock(existsSync(f) ? readFileSync(f, "utf8") : "");
};

export const writeLock = (dir: string, lock: Map<string, LockEntry[]>) => writeFileSync(join(dir, LOCK), formatLock(lock));
